function vzyat_yazyk() {
    for (const chast of document.cookie.split(";")) {
        const para = chast.trim().split("=");
        if (para[0] === "yazyk") { return para[1]; }
    }
    return "ru";
}

const YAZYK = vzyat_yazyk();

const AVTOPEREVOD = {};
const V_OCHEREDI = new Set();
const propushchennye = new Set();
let taymer_ocheredi = null;
let idet_perevod = false;

function zapomnit_dlya_perevoda(fraza) {
    if (YAZYK === "ru") { return; }
    if (AVTOPEREVOD[fraza] !== undefined) { return; }
    if (V_OCHEREDI.has(fraza)) { return; }

    V_OCHEREDI.add(fraza);

    if (taymer_ocheredi === null) {
        taymer_ocheredi = setTimeout(otpravit_ochered, 400);
    }
}

async function otpravit_ochered() {
    taymer_ocheredi = null;

    if (V_OCHEREDI.size === 0) { return; }

    const spisok = Array.from(V_OCHEREDI).slice(0, 20);
    for (const f of spisok) { V_OCHEREDI.delete(f); }

    try {
        const otvet = await fetch("/api/perevesti", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ frazy: spisok, yazyk: YAZYK })
        });

        const d = await otvet.json();

        let est_novoe = false;
        for (const fraza in d.perevody) {
            AVTOPEREVOD[fraza] = d.perevody[fraza];
            est_novoe = true;
        }

        for (const fraza of spisok) {
            if (AVTOPEREVOD[fraza] === undefined) {
                AVTOPEREVOD[fraza] = null;
            }
        }

        if (est_novoe) {
            idet_perevod = true;
            obrabotat_uzel(document.body);
            idet_perevod = false;
        }

    } catch (e) {
        for (const fraza of spisok) {
            AVTOPEREVOD[fraza] = null;
        }
    }

    if (V_OCHEREDI.size > 0) {
        taymer_ocheredi = setTimeout(otpravit_ochered, 400);
    }
}

function perevesti(fraza) {
    if (YAZYK === "ru" || !fraza) { return fraza; }

    const chistyy = String(fraza).trim();
    if (chistyy.length < 2) { return fraza; }
    if (!/[а-яА-ЯёЁ]/.test(chistyy)) { return fraza; }

    if (SLOVAR[chistyy] && SLOVAR[chistyy][YAZYK]) {
        return fraza.replace(chistyy, SLOVAR[chistyy][YAZYK]);
    }

    const chisla = chistyy.match(/\d+/g);
    const shablon = chistyy.replace(/\d+/g, "{n}");

    if (SLOVAR[shablon] && SLOVAR[shablon][YAZYK]) {
        let itog = SLOVAR[shablon][YAZYK];
        if (chisla) {
            for (const chislo of chisla) {
                itog = itog.replace("{n}", chislo);
            }
        }
        return fraza.replace(chistyy, itog);
    }

    if (AVTOPEREVOD[chistyy]) {
        return fraza.replace(chistyy, AVTOPEREVOD[chistyy]);
    }

    if (AVTOPEREVOD[chistyy] === undefined) {
        zapomnit_dlya_perevoda(chistyy);

        if (!propushchennye.has(shablon)) {
            propushchennye.add(shablon);
            console.info('Нет в словаре, отправлено на автоперевод:\n    "' + shablon +
                         '": { en: "", es: "", de: "", fr: "", zh: "" },');
        }
    }

    return fraza;
}

function t(klyuch) {
    const russkiy = STARYE_KLYUCHI[klyuch] || klyuch;
    return perevesti(russkiy);
}

function propustit(uzel) {
    let el = uzel.nodeType === 3 ? uzel.parentElement : uzel;
    while (el && el !== document.body) {
        for (const selektor of NE_PEREVODIT) {
            if (el.matches && el.matches(selektor)) { return true; }
        }
        if (el.classList && el.classList.contains("ne-perevodit")) { return true; }
        el = el.parentElement;
    }
    return false;
}

function obrabotat_uzel(uzel) {
    if (uzel.nodeType === 3) {
        if (propustit(uzel)) { return; }
        const novyy = perevesti(uzel.textContent);
        if (novyy !== uzel.textContent) { uzel.textContent = novyy; }
        return;
    }

    if (uzel.nodeType !== 1) { return; }
    if (propustit(uzel)) { return; }

    if (uzel.placeholder) {
        const novyy = perevesti(uzel.placeholder);
        if (novyy !== uzel.placeholder) { uzel.placeholder = novyy; }
    }

    if (uzel.tagName === "OPTION" && uzel.textContent) {
        const novyy = perevesti(uzel.textContent);
        if (novyy !== uzel.textContent) { uzel.textContent = novyy; }
    }

    for (const rebenok of uzel.childNodes) {
        obrabotat_uzel(rebenok);
    }
}

function perevesti_stranicu() {
    if (YAZYK === "ru") { return; }

    idet_perevod = true;

    for (const el of document.querySelectorAll("[data-t]")) {
        el.textContent = t(el.getAttribute("data-t"));
    }
    for (const el of document.querySelectorAll("[data-tp]")) {
        el.placeholder = t(el.getAttribute("data-tp"));
    }

    obrabotat_uzel(document.body);

    idet_perevod = false;
}

if (YAZYK !== "ru") {
    const nablyudatel = new MutationObserver(function (izmeneniya) {
        if (idet_perevod) { return; }
        idet_perevod = true;

        for (const izm of izmeneniya) {
            if (izm.type === "childList") {
                for (const uzel of izm.addedNodes) {
                    obrabotat_uzel(uzel);
                }
            } else if (izm.type === "characterData") {
                obrabotat_uzel(izm.target);
            }
        }

        idet_perevod = false;
    });

    document.addEventListener("DOMContentLoaded", function () {
        perevesti_stranicu();
        nablyudatel.observe(document.body, {
            childList: true,
            subtree: true,
            characterData: true
        });
    });

    const staryy_alert = window.alert;
    window.alert = function (soobshenie) {
        staryy_alert(perevesti(soobshenie));
    };

    const staryy_confirm = window.confirm;
    window.confirm = function (soobshenie) {
        return staryy_confirm(perevesti(soobshenie));
    };
}

function ekran(tekst) {
    if (tekst === null || tekst === undefined) { return ""; }
    return String(tekst)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#39;");
}